  homepage "https://github.com/Akinus21/akai-agent"
  version "0.0.24"
  license "MIT"
  depends_on "cmake"
  depends_on "gcc"
  depends_on "git"
  on_linux do
    url "https://github.com/Akinus21/akai-agent/releases/download/v0.0.24/akai-agent"
    sha256 "4ff4f35725fdc3ea6100736dd5228417ac618d19b86c7a88cd72692d78f0037a"
  end
  def install
    bin.install "akai-agent" => "akai-agent"
  end
  test do
    assert_match "akai-agent", shell_output("#{bin}/akai-agent --help")
  end
end
