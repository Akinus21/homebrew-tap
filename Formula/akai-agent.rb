    sha256 "085d00489b6220235caec03be68178e6e2bce10a1101757be6cad632cc4e0038"
  end
  def install
    bin.install "akai-agent" => "akai-agent"
  end
  test do
    assert_match "akai-agent", shell_output("#{bin}/akai-agent --help")
  end
end
